"""
Build the SQLite claims database and run the SQL layer end to end.

Steps
  1. Create schema                         (sql/01_schema.sql)
  2. Load raw CSVs into tables
  3. Run data-quality checks               (sql/02_data_quality_checks.sql) -> reports/data_quality_report.md
  4. Run business EDA queries              (sql/03_exploratory_analysis.sql) -> reports/sql_insights.md
  5. Create base view + red-flag rules     (sql/04_red_flag_rules.sql)
  6. Build modelling table                 (sql/05_feature_engineering.sql) -> data/processed/claim_features.csv

Usage:
    python src/build_database.py
"""
from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
PROCESSED = ROOT / "data" / "processed"
SQL = ROOT / "sql"
REPORTS = ROOT / "reports"
DB_PATH = ROOT / "data" / "insurance_claims.db"

TABLE_LOAD_ORDER = ["customers", "agents", "garages", "policies", "claims"]


def md_table(df: pd.DataFrame) -> str:
    """Minimal DataFrame -> GitHub markdown table (no external deps)."""
    def fmt(v):
        if pd.isna(v):
            return ""
        if isinstance(v, float):
            return f"{v:,.2f}".rstrip("0").rstrip(".") if abs(v) < 1e6 else f"{v:,.0f}"
        return str(v)
    head = "| " + " | ".join(df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def split_statements(sql_text: str) -> list[str]:
    return [s.strip() for s in sql_text.split(";") if re.sub(r"--.*", "", s).strip()]


def main() -> None:
    PROCESSED.mkdir(parents=True, exist_ok=True)
    REPORTS.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)

    # 1. schema
    con.executescript((SQL / "01_schema.sql").read_text())

    # 2. load
    for t in TABLE_LOAD_ORDER:
        df = pd.read_csv(RAW / f"{t}.csv")
        if t == "claims":
            df["incident_hour"] = df["incident_hour"].astype("Int64")
        df.to_sql(t, con, if_exists="append", index=False)
        print(f"loaded {t:<10} {len(df):>7,} rows")
    con.commit()

    # 3. data quality
    dq_rows = []
    for stmt in split_statements((SQL / "02_data_quality_checks.sql").read_text()):
        dq_rows.append(pd.read_sql(stmt, con))
    dq = pd.concat(dq_rows, ignore_index=True)
    dq["issue_pct"] = (100 * dq["issue_count"] / dq["total_rows"]).round(2)
    dq["status"] = dq["issue_count"].map(lambda n: "PASS" if n == 0 else "REVIEW")
    (REPORTS / "data_quality_report.md").write_text(
        "# Data Quality Report\n\nGenerated by `src/build_database.py` from "
        "`sql/02_data_quality_checks.sql`.\n\n" + md_table(dq) +
        "\n\n**Handling:** report-before-incident rows get `report_delay_days = NULL` plus a "
        "`dq_report_before_incident` flag; missing `incident_hour` is imputed as -1 with a "
        "missing-indicator; missing income gets a missing-indicator and NULL ratio. "
        "No rows are dropped, so investigators still see every claim.\n")
    print("\nData-quality checks:\n", dq[["check_name", "issue_count", "status"]].to_string(index=False))

    # 4. EDA queries
    out = ["# SQL Business Insights\n",
           "Generated by `src/build_database.py` from `sql/03_exploratory_analysis.sql`.\n"]
    for stmt in split_statements((SQL / "03_exploratory_analysis.sql").read_text()):
        title = re.search(r"--\s*(Q\d+:.*)", stmt)
        res = pd.read_sql(stmt, con)
        out.append(f"\n## {title.group(1).strip() if title else 'Query'}\n\n{md_table(res)}\n")
    (REPORTS / "sql_insights.md").write_text("\n".join(out))

    # 5 + 6. views and features
    con.executescript((SQL / "04_red_flag_rules.sql").read_text())
    con.executescript((SQL / "05_feature_engineering.sql").read_text())
    feats = pd.read_sql("SELECT * FROM claim_features ORDER BY claim_id", con)
    feats.to_csv(PROCESSED / "claim_features.csv", index=False)
    print(f"\nclaim_features: {feats.shape[0]:,} rows x {feats.shape[1]} cols "
          f"-> data/processed/claim_features.csv")
    con.close()


if __name__ == "__main__":
    main()
